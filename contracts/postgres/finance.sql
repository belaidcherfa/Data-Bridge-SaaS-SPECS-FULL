-- contract=postgres-finance version=1 status=DRAFT owner_task=FIN-010 decisions=D-04,D-12,D-13,D-20,D-25,D-35 last_changed=2026-09-28
-- Reference DDL for the PostgreSQL schema `finance` (lane K5, domain FIN). Alembic migrations must converge to it
-- (schema-diff test, CONVENTIONS §1/§10). Contributing tasks: FIN-010-S01 (periods, close, statements),
-- FIN-101-S01 (billing references), FIN-105-S01 (customer-approved rate tables), FIN-009-S11 (reconciliation runs
-- and explanations), FIN-104-S02 (maturity overrides), FIN-107-S01 (correction cases, prior-period adjustments).
--
-- Rules applied (CONVENTIONS §10):
--   * every table is tenant-owned: tenant_id, id (UUIDv7 generated by the application), created_at, updated_at,
--     revision, PRIMARY KEY (tenant_id, id), composite foreign keys including tenant_id, tenant-leading indexes;
--   * ROW LEVEL SECURITY ENABLE + FORCE with the SEC RLS standard policy (fallback template of the contract brief
--     until K2 publishes contracts/postgres/platform*.sql; replace the policy body with K2's template verbatim);
--   * status columns are text + CHECK generated from contracts/state-machines/<machine>.yaml;
--   * money and rates are numeric(38,12) (NUMBER(38,12) in Snowflake); never float;
--   * JSONB only for versioned, schema-validated documents (*_json + *_schema_version);
--   * no analytical fact mirror (PRD §57): charges, attribution rows, reconciliation differences and statement lines
--     live in Snowflake; this schema stores identifiers, statuses, bounded counts, issued-document totals and
--     references to Snowflake publications (pub_seq) and CONFIG versions.
--
-- Cross-lane references kept as logical columns (no FK because the target file belongs to another lane; the lead
-- adds the FKs when the files are merged — see contracts/_handoffs/K5.md):
--   tenant_id            -> tenant.tenant(id)                         (K2)
--   *_by (member ids)    -> tenant.membership(tenant_id, id)          (K2)  -- never e-mail or names (D-10)
--   organization_id      -> connection.organization(tenant_id, id)    (K3)
--   account_id           -> connection.account(tenant_id, id)         (K3)  -- account inventory incl. unconnected
--   approval_id          -> K2 approval object (SEC Appendix C.4, machine `approval`)
--   config_publication_id-> K2 config publication record (CTL-005-S03)
--   pub_seq              -> Snowflake PUBLICATION.PUBLICATION(pub_seq) (K4, ADR-014)
--
-- Requires extension btree_gist (exclusion constraint on rate lines). Created here idempotently; the platform
-- baseline (K2/K1) should own extension creation.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE SCHEMA IF NOT EXISTS finance;

COMMENT ON SCHEMA finance IS 'FIN control plane: periods, close, statements, billing references, approved rate tables, reconciliation runs/explanations, corrections. Owner lane K5. No analytical fact mirror.';

