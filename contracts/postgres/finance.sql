CREATE TABLE finance.close_policy (
    tenant_id                         uuid          NOT NULL,
    id                                uuid          NOT NULL,
    close_requires_second_approver    boolean       NOT NULL DEFAULT true,
    second_approver_waiver_ack_by     uuid          NULL,
    second_approver_waiver_ack_at     timestamptz   NULL,
    c5_required_for_close             boolean       NOT NULL DEFAULT true,
    c5_required_for_reconciled        boolean       NOT NULL DEFAULT false,
    min_account_day_coverage          numeric(38,12) NOT NULL DEFAULT 1,
    restate_abs_threshold             numeric(38,12) NOT NULL DEFAULT 100,
    restate_rel_threshold             numeric(38,12) NOT NULL DEFAULT 0.005,
    close_preview_ttl_seconds         integer       NOT NULL DEFAULT 86400,
    record_retention_days             integer       NOT NULL DEFAULT 400,
    config_publication_id             uuid          NULL,
    published_config_version          bigint        NULL,
    created_at                        timestamptz   NOT NULL DEFAULT now(),
    updated_at                        timestamptz   NOT NULL DEFAULT now(),
    revision                          bigint        NOT NULL DEFAULT 1,
    CONSTRAINT close_policy_pk PRIMARY KEY (tenant_id, id),
    CONSTRAINT close_policy_one_per_tenant UNIQUE (tenant_id),
    CONSTRAINT close_policy_coverage_ck CHECK (min_account_day_coverage >= 0 AND min_account_day_coverage <= 1),
    CONSTRAINT close_policy_abs_ck CHECK (restate_abs_threshold >= 0),
    CONSTRAINT close_policy_rel_ck CHECK (restate_rel_threshold >= 0 AND restate_rel_threshold <= 1),
    CONSTRAINT close_policy_ttl_ck CHECK (close_preview_ttl_seconds BETWEEN 3600 AND 86400),
    CONSTRAINT close_policy_retention_ck CHECK (record_retention_days BETWEEN 400 AND 2557),
    -- Owner question Q3: the second approver may be waived only with an explicit tenant-owner acknowledgement.
    CONSTRAINT close_policy_waiver_ck CHECK (
        close_requires_second_approver
        OR (second_approver_waiver_ack_by IS NOT NULL AND second_approver_waiver_ack_at IS NOT NULL)
    ),
    CONSTRAINT close_policy_revision_ck CHECK (revision >= 1)
);
COMMENT ON TABLE finance.close_policy IS 'Owner FIN-010-S02/FIN-107-S02. One row per tenant. Published to CONFIG.FINANCE_POLICY (kind FINANCE_POLICY) through the D-04 config publisher; dbt period roll-up (FIN-009-S10) reads the published version.';
COMMENT ON COLUMN finance.close_policy.second_approver_waiver_ack_by IS 'Membership id of the tenant Owner who acknowledged the waiver (INTERNAL id; never a name).';
COMMENT ON COLUMN finance.close_policy.min_account_day_coverage IS 'Minimum share (0..1) of eligible (account, day) pairs of the period with contiguous charge-authority coverage before close (default 1 = complete).';
COMMENT ON COLUMN finance.close_policy.restate_abs_threshold IS 'Materiality: restatement is proposed when |delta| >= max(restate_abs_threshold, restate_rel_threshold x |closed period total|) in the period currency (owner Q4 default 100 / 0.005).';
COMMENT ON COLUMN finance.close_policy.record_retention_days IS 'S3 Object Lock GOVERNANCE retention for RECORD artifacts (statements, references): default max(400 d, contract), up to 7 years (ADR-009 amendment item 5, owner Q7).';

